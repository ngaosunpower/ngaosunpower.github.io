  var DICT = { en: null, zh: ZH, sw: SW };
  var STORE = 'ngp-lang';

  var textRecords = null;
  var attrRecords = null;
  var current = 'en';

  function norm(s) {
    return String(s).replace(/\s+/g, ' ').trim();
  }

  function has(obj, key) {
    return obj && Object.prototype.hasOwnProperty.call(obj, key);
  }

  /* Record the English original of every text node and attribute once, so
     switching languages is always relative to the same source. */
  function collect() {
    textRecords = [];
    attrRecords = [];

    var walker = document.createTreeWalker(
      document.body,
      NodeFilter.SHOW_TEXT,
      {
        acceptNode: function (n) {
          var p = n.parentNode;
          if (!p || !p.nodeName) return NodeFilter.FILTER_REJECT;
          var tag = p.nodeName.toUpperCase();
          if (tag === 'SCRIPT' || tag === 'STYLE' || tag === 'TITLE' || tag === 'NOSCRIPT') {
            return NodeFilter.FILTER_REJECT;
          }
          if (p.closest && p.closest('svg')) return NodeFilter.FILTER_REJECT;
          if (!norm(n.nodeValue)) return NodeFilter.FILTER_REJECT;
          return NodeFilter.FILTER_ACCEPT;
        }
      },
      false
    );

    var n;
    while ((n = walker.nextNode())) textRecords.push({ node: n, en: n.nodeValue });

    var names = ['placeholder', 'aria-label', 'alt', 'title'];
    var els = document.querySelectorAll('[placeholder],[aria-label],[alt],[title]');
    for (var i = 0; i < els.length; i++) {
      var el = els[i];
      if (el.closest && el.closest('svg')) continue;
      for (var j = 0; j < names.length; j++) {
        var a = names[j];
        if (el.hasAttribute(a) && el.getAttribute(a).trim()) {
          attrRecords.push({ el: el, name: a, en: el.getAttribute(a) });
        }
      }
    }
  }

  function setMeta(kind, key, value) {
    if (!value) return;
    var el = document.querySelector('meta[' + kind + '="' + key + '"]');
    if (el) el.setAttribute('content', value);
  }

  function apply(lang) {
    if (!textRecords) collect();

    var d = DICT[lang] || null;
    var i, key, value;

    for (i = 0; i < textRecords.length; i++) {
      var r = textRecords[i];
      key = norm(r.en);
      value = has(d, key) ? d[key] : null;
      if (value === null) {
        if (r.node.nodeValue !== r.en) r.node.nodeValue = r.en;
        continue;
      }
      var lead = /^\s/.test(r.en) ? ' ' : '';
      var trail = /\s$/.test(r.en) ? ' ' : '';
      r.node.nodeValue = lead + value + trail;
    }

    var ad = lang === 'en' ? null : ATTR[lang];
    for (i = 0; i < attrRecords.length; i++) {
      var a = attrRecords[i];
      var av = has(ad, a.en) ? ad[a.en] : null;
      a.el.setAttribute(a.name, av === null ? a.en : av);
    }

    var m = META[lang] || META.en;
    document.title = m.title;
    setMeta('name', 'description', m.desc);
    setMeta('property', 'og:title', m.ogTitle);
    setMeta('property', 'og:description', m.ogDesc);
    setMeta('property', 'og:locale', m.locale);
    document.documentElement.setAttribute('lang', m.lang);

    current = lang;
    var selects = document.querySelectorAll('.lang__select');
    for (i = 0; i < selects.length; i++) {
      if (selects[i].value !== lang) selects[i].value = lang;
    }
  }

  function setLang(lang) {
    if (lang !== 'en' && lang !== 'zh' && lang !== 'sw') lang = 'en';
    apply(lang);
    try { localStorage.setItem(STORE, lang); } catch (e) {}
  }

